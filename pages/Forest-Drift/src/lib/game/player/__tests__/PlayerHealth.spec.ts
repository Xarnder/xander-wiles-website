import { describe, expect, it } from 'vitest';
import {
	HEALTH_GRACE_MS,
	HEALTH_MAX,
	canRespawn,
	createHealthState,
	damageHealth,
	healthAt,
	healthSnapshot,
	restoreHealth,
	reviveHealth,
	savedHealthValue
} from '../PlayerHealth';

/** A state past its grace period, so damage applies. */
function settled(points = HEALTH_MAX) {
	return createHealthState(-HEALTH_GRACE_MS, points);
}

describe('PlayerHealth', () => {
	it('starts full and ignores damage during the grace period', () => {
		const state = createHealthState(0);
		expect(healthAt(state, 0)).toBe(36);
		expect(damageHealth(state, 5, 1999).applied).toBe(0);
		expect(damageHealth(state, 5, 2000).applied).toBe(5);
	});

	it('clamps at zero and marks death once', () => {
		const hit = damageHealth(settled(10), 50, 0);
		expect(hit.applied).toBe(10);
		expect(hit.state.dead).toBe(true);
		expect(healthAt(hit.state, 100_000)).toBe(0);
		expect(damageHealth(hit.state, 5, 1).applied).toBe(0);
	});

	it('ignores zero, negative and non-finite damage', () => {
		const state = settled();
		for (const amount of [0, -3, Number.NaN, Number.POSITIVE_INFINITY]) {
			expect(damageHealth(state, amount, 0).applied).toBe(0);
		}
	});

	it('regains a point 11 s after the last hit, then one every 3 s', () => {
		const { state } = damageHealth(settled(), 10, 0);
		expect(healthAt(state, 10_999)).toBe(26);
		expect(healthAt(state, 11_000)).toBe(27);
		expect(healthAt(state, 13_999)).toBe(27);
		expect(healthAt(state, 14_000)).toBe(28);
	});

	it('recovers from 1 point to full in about 113 s and never overshoots', () => {
		const { state } = damageHealth(settled(), 35, 0);
		expect(healthAt(state, 0)).toBe(1);
		expect(healthAt(state, 112_999)).toBe(35);
		expect(healthAt(state, 113_000)).toBe(36);
		expect(healthAt(state, 10_000_000)).toBe(36);
	});

	it('restarts the regeneration delay on each hit, from the regenerated value', () => {
		const first = damageHealth(settled(), 10, 0).state;
		const second = damageHealth(first, 1, 20_000);
		// 26 + 4 regenerated by 20 s, minus 1.
		expect(healthAt(second.state, 20_000)).toBe(29);
		expect(healthAt(second.state, 30_999)).toBe(29);
		expect(healthAt(second.state, 31_000)).toBe(30);
	});

	it('only allows respawning 3 s after the knockout', () => {
		const dead = damageHealth(settled(), 36, 1000).state;
		expect(canRespawn(dead, 3999)).toBe(false);
		expect(canRespawn(dead, 4000)).toBe(true);
		expect(canRespawn(dead, 3600, 500)).toBe(true);
		expect(canRespawn(settled(), 10_000)).toBe(false);
	});

	it('revives to full with a fresh grace period', () => {
		const state = reviveHealth(5000);
		expect(healthAt(state, 5000)).toBe(36);
		expect(state.dead).toBe(false);
		expect(damageHealth(state, 3, 6000).applied).toBe(0);
	});

	it('restores saved values defensively, never into a death', () => {
		expect(healthAt(restoreHealth(20, 0), 0)).toBe(20);
		expect(healthAt(restoreHealth(20.4, 0), 0)).toBe(20);
		expect(healthAt(restoreHealth(0, 0), 0)).toBe(36);
		expect(healthAt(restoreHealth(-5, 0), 0)).toBe(36);
		expect(healthAt(restoreHealth(1e9, 0), 0)).toBe(36);
		expect(healthAt(restoreHealth(undefined, 0), 0)).toBe(36);
		expect(healthAt(restoreHealth('12', 0), 0)).toBe(36);
		expect(healthAt(restoreHealth(Number.NaN, 0), 0)).toBe(36);
		expect(restoreHealth(20, 0).graceUntil).toBe(HEALTH_GRACE_MS);
	});

	it('normalises values for saving', () => {
		expect(savedHealthValue(20)).toBe(20);
		expect(savedHealthValue(0)).toBe(36);
		expect(savedHealthValue(99)).toBe(36);
		expect(savedHealthValue(Number.NaN)).toBeUndefined();
		expect(savedHealthValue('3')).toBeUndefined();
	});

	it('reports the low state at 25% and below', () => {
		expect(healthSnapshot(settled(10), 0).low).toBe(false);
		expect(healthSnapshot(settled(9), 0).low).toBe(true);
		const dead = damageHealth(settled(1), 1, 0).state;
		expect(healthSnapshot(dead, 0)).toEqual({ current: 0, max: 36, dead: true, low: false });
	});
});
