/**
 * Build a compact unicode → Fluent slug map from @fluentui-emoji/svg + unicode-emoji-json.
 * Run: npm run build:emoji
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fluentPkg = require(join(root, 'node_modules/@fluentui-emoji/svg/package.json'));
const fluent = JSON.parse(
  readFileSync(join(root, 'node_modules/@fluentui-emoji/svg/metadata.json'), 'utf8')
);
const unicode = JSON.parse(
  readFileSync(join(root, 'node_modules/unicode-emoji-json/data-by-emoji.json'), 'utf8')
);

const fluentSlugs = new Set(fluent.emojis.map((e) => e.slug));
const fluentByName = new Map(fluent.emojis.map((e) => [e.name.toLowerCase(), e.slug]));

const NAME_ALIASES = {
  'smiling face with open hands': 'hugging-face',
  'enraged face': 'pouting-face',
  'face with crossed-out eyes': 'knocked-out-face',
  'person blond hair': 'person-blonde-hair-default',
  'man blond hair': 'man-blonde-hair-default',
  'woman blond hair': 'woman-blonde-hair-default',
  'deaf person': 'person-deaf-default',
  'deaf man': 'man-deaf-default',
  'deaf woman': 'woman-deaf-default',
  merperson: 'person-merpeople-default',
  merman: 'man-merpeople-default',
  mermaid: 'woman-merpeople-default',
};

function pickSlug(candidates) {
  for (const raw of candidates) {
    if (!raw) continue;
    const c = String(raw).toLowerCase().replace(/_/g, '-').replace(/\s+/g, '-');
    if (fluentSlugs.has(c)) return c;
    if (fluentSlugs.has(`${c}-default`)) return `${c}-default`;
  }
  return null;
}

function slugFromInfo(info) {
  const hyphen = info.slug.replace(/_/g, '-');
  const blonde = hyphen.replace(/blond/g, 'blonde');
  const alias = NAME_ALIASES[info.name.toLowerCase()];
  const fromName = fluentByName.get(info.name.toLowerCase());
  return pickSlug([
    hyphen,
    blonde,
    `${hyphen}-default`,
    `${blonde}-default`,
    `person-${hyphen}-default`,
    `person-${blonde}-default`,
    hyphen.replace(/-person$/, '') && `person-${hyphen.replace(/-person$/, '')}-default`,
    hyphen.startsWith('man-') ? `${blonde}-default` : null,
    hyphen.startsWith('woman-') ? `${blonde}-default` : null,
    alias,
    fromName,
  ]);
}

function stripVS(s) {
  return s.replace(/\uFE0F/g, '').replace(/\uFE0E/g, '');
}

const map = {};
let hit = 0;
for (const [glyph, info] of Object.entries(unicode)) {
  const slug = slugFromInfo(info);
  if (!slug) continue;
  hit += 1;
  map[glyph] = slug;
  const stripped = stripVS(glyph);
  if (stripped && stripped !== glyph && !map[stripped]) map[stripped] = slug;
}

const outPath = join(root, 'js/fluent-emoji-slugs.js');
const body = `/** Generated by scripts/build-fluent-emoji-map.mjs — do not edit. */
export const FLUENT_EMOJI_VERSION = ${JSON.stringify(fluentPkg.version)};
export const FLUENT_EMOJI_STYLE = 'modern';
export const FLUENT_EMOJI_SLUGS = ${JSON.stringify(map)};
`;
writeFileSync(outPath, body);
console.log(`Wrote ${outPath} (${hit} glyphs, ${Object.keys(map).length} keys, v${fluentPkg.version})`);
